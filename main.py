"""Feature Extraction 1 – Statistical Features"""

from scipy.stats import skew, kurtosis
import time

def extract_statistical_features(X_data):
    start_time = time.time()
    features = []
    for row in X_data:
        row_features = [
            np.mean(row),
            np.std(row),
            np.max(row),
            np.min(row),
            np.ptp(row),
            skew(row),
            kurtosis(row)
        ]
        features.append(row_features)
    print(f"Statistical Extraction complete in {time.time() - start_time:.2f} seconds.")
    return np.array(features)

X_stat = extract_statistical_features(X_raw)
print(f"Statistical Features Shape: {X_stat.shape}")

"""Feature Extraction 2 – Morphological Features"""

def extract_morphological_features(X_data):
    start_time = time.time()
    features = []
    for row in X_data:
        max_val = np.max(row)
        min_val = np.min(row)
        max_idx = np.argmax(row)
        min_idx = np.argmin(row)
        centered = row - np.mean(row)
        zero_crossings = np.sum(np.diff(np.sign(centered)) != 0)
        qrs_width = np.sum(row > (0.5 * max_val))
        row_features = [
            max_val,
            max_idx,
            min_val,
            min_idx,
            max_val - min_val,
            abs(max_idx - min_idx),
            np.sum(row ** 2),
            np.sum(np.abs(row)),
            zero_crossings,
            qrs_width,
            np.percentile(row, 25),
            np.percentile(row, 75)
        ]
        features.append(row_features)
    print(f"Morphological Extraction complete in {time.time() - start_time:.2f} seconds.")
    return np.array(features)

