"""SVM - Statistical Features"""

import matplotlib.pyplot as plt
import seaborn as sns
import numpy as np
from sklearn.model_selection import StratifiedKFold
from sklearn.preprocessing import StandardScaler
from sklearn.svm import LinearSVC
from sklearn.metrics import accuracy_score, f1_score, classification_report, confusion_matrix


print(f"Verified X_features shape: {X_stat.shape}")
print(f"Verified y shape: {y.shape}")
print("-" * 50)
print("Starting 5-Fold Stratified CV with Balanced Linear SVC (Statistical Features)...")

skf = StratifiedKFold(n_splits=5, shuffle=True, random_state=42)

acc_scores = []
f1_scores = []

for fold, (train_idx, test_idx) in enumerate(skf.split(X_stat, y), 1):
    X_train, X_test = X_stat[train_idx], X_stat[test_idx]
    y_train, y_test = y[train_idx], y[test_idx]

    scaler = StandardScaler()
    X_train_scaled = scaler.fit_transform(X_train)
    X_test_scaled = scaler.transform(X_test)

    model = LinearSVC(class_weight='balanced', random_state=42, max_iter=1000, dual=False)
    model.fit(X_train_scaled, y_train)
    y_pred = model.predict(X_test_scaled)

    acc = accuracy_score(y_test, y_pred)
    f1 = f1_score(y_test, y_pred, average='macro')

    acc_scores.append(acc)
    f1_scores.append(f1)

    print(f"Fold {fold} - Accuracy: {acc:.4f}, Macro-F1: {f1:.4f}")

    if fold == 5:
        cm = confusion_matrix(y_test, y_pred)
        print("\n--- Final Fold Evaluation Details ---")
        print("Confusion Matrix:\n", cm)
        print("\nClassification Report:\n", classification_report(y_test, y_pred, target_names=["N", "S", "V", "F", "Q"]))

        plt.figure(figsize=(6, 5))
        sns.heatmap(cm, annot=True, fmt='d', cmap='Blues', xticklabels=["N", "S", "V", "F", "Q"], yticklabels=["N", "S", "V", "F", "Q"])
        plt.title("Confusion Matrix: SVM - Statistical Features (Fold 5)", fontsize=12, fontweight='bold', pad=10)
        plt.xlabel('Predicted Label')
        plt.ylabel('True Label')
