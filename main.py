import pywt
import time

warnings.filterwarnings('ignore')

def extract_dwt_features(X_data):
    print("Extracting DWT Features")
    start_time = time.time()
    features = []
    for row in X_data:
        coeffs = pywt.wavedec(row, 'db4', level=4)
        row_features = []
        for band in coeffs:
            row_features.extend([
                np.mean(band),
                np.std(band),
                np.sum(np.square(band)),
                np.max(band)
            ])
        features.append(row_features)
    print(f"Extraction complete in {time.time() - start_time:.2f} seconds.\n")
    return np.array(features)

